def source_dir(key):
    return SOURCES_DIR / key


def resolve(ref):
    """'phoenix:phoenix-ios/phoenix-ios' -> the checked-out path."""
    key, _, path = ref.partition(':')
    return source_dir(key) / path


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=1, sort_keys=False, ensure_ascii=False) + '\n')


def dumps(value, width=150, indent=''):
    """JSON for files people edit: anything that fits on one line stays on one line."""
    flat = json.dumps(value, ensure_ascii=False)
    if len(indent) + len(flat) <= width or not isinstance(value, (dict, list)) or not value:
        return flat
    inner = indent + ' '
    if isinstance(value, dict):
        items = [f'{inner}{json.dumps(k)}: {dumps(v, width, inner)}' for k, v in value.items()]
        return '{\n' + ',\n'.join(items) + '\n' + indent + '}'
    return '[\n' + ',\n'.join(inner + dumps(v, width, inner) for v in value) + '\n' + indent + ']'


def write_config(path, value):
    path.write_text(dumps(value) + '\n')


def strip_rust_tests(text):
    """Remove #[cfg(test)] / #[cfg(all(test, ...))] modules, which Rust keeps inside source files."""
    out, i = [], 0
    attr = re.compile(r'#\[cfg\((?:all\()?test\b[^\]]*\]\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+\w+\s*\{')
    while True:
        m = attr.search(text, i)
        if not m:
            out.append(text[i:])
            return ''.join(out)
        out.append(text[i:m.start()])
        j, depth = m.end(), 1
        while depth and j < len(text):
            c = text[j]
            if text.startswith('//', j):
                j = text.find('\n', j)
                j = len(text) if j < 0 else j
                continue
            if text.startswith('/*', j):
                j = text.find('*/', j) + 2
                continue
            r = re.match(r'r(#*)"', text[j:j + 8]) if c == 'r' and not text[j - 1].isalnum() else None
            if r:
                close = '"' + r.group(1)
                j = text.find(close, j + len(r.group(0))) + len(close)
                continue
            if c == '"':
                j += 1
                while text[j] != '"':
                    j += 2 if text[j] == '\\' else 1
                j += 1
                continue
            ch = re.match(r"'(?:\\.|[^\\'])'|b'(?:\\.|[^\\'])'", text[j:j + 12])
            if ch:
                j += len(ch.group(0))
                continue
            depth += c == '{'
            depth -= c == '}'
            j += 1
        i = j


def unclaimed(spec):
    """Directories in a wallet's `complete` trees that none of its code parts counts. A tree listed
    there (e.g. winnow:Lean) must be counted in full, or left out by name in `skip`, so a wallet that moves
    code into a new folder fails the build instead of quietly shrinking."""
    counted = [resolve(ref).resolve() for refs in spec['code'].values() for ref in refs]
    counted += [resolve(ref).resolve() for ref in left_out(spec)]
    missing = []
    for tree in spec.get('complete', []):
        for d in sorted(p for p in resolve(tree).iterdir() if p.is_dir()):
            d = d.resolve()
            if not any(c == d or d in c.parents or c in d.parents for c in counted):
                missing.append(f'{tree}/{d.name}')
    return missing


def left_out(spec):
    """Paths a wallet's own code leaves out: `skip` (never built into the app) and `vendored`
    (third-party copies, counted as vendored code instead)."""
    return spec.get('skip', []) + spec.get('vendored', [])


def counted_files(refs, skip=()):
    """The files a part of a wallet ships: programming-language sources that build into the
    iPhone app, minus tests, other platforms and generated files. Returns (kept, generated)."""
    kept, generated = [], []
    left_out = [resolve(s).resolve() for s in skip]
    for ref in refs:
        src = resolve(ref)
        if not src.exists():
            raise SystemExit(f'{ref} does not exist at the pinned revision; update the paths in sources.json')
        files = [src] if src.is_file() else sorted(f for f in src.rglob('*') if f.is_file())
        for f in files:
            rel = str(f.relative_to(SOURCES_DIR))
            if any(s in f.resolve().parents for s in left_out):
                continue
            if f.suffix not in EXTENSIONS or SKIP_DIRS & set(f.relative_to(SOURCES_DIR).parts[:-1]):
                continue
            if TEST_FILE.search(rel) or TEST_PATH.search('/' + rel):
                continue
            if GENERATED.search(f.read_text(errors='ignore')[:1500]):
                generated.append(rel)
                continue
            kept.append(f)
    return kept, generated


PROOF_STAGE = ROOT / '.stage-proofs'


def lean_imports(roots, search):
    """The Lean files that `roots` import, directly or not, themselves included."""
    import lean
    search = [resolve(r) for r in search]
    todo = [resolve(r) for r in roots]
    seen = set()
    while todo:
        f = todo.pop().resolve()
        if f in seen:
            continue
        seen.add(f)
        for module in lean.imports(f.read_text(errors='ignore')):
            rel = Path(*module.split('.')).with_suffix('.lean')
            for base in search:
                if (base / rel).exists():
                    todo.append(base / rel)
                    break
    return seen


def lean_closure(spec):
    """(what the app builds, what its proofs read) for a wallet with `lean` roots, else None. The app's
    roots and everything they import build into the app. A Lean library may also hold proofs, and the
    specification they are proved against, in modules the app never imports: those are what the proof
    roots import and the app's do not. Anything else (an umbrella module, the project manifest) is
    neither."""
    lean_spec = spec.get('lean')
    if not lean_spec:
        return None
    app = lean_imports(lean_spec['roots'], lean_spec['search'])
    return app, lean_imports(lean_spec.get('proofs', []), lean_spec['search']) - app


def stage(refs, skip=(), closure=None):
    """Copy a part's counted files into .stage/ and return them, with the generated files left out and the
    Lean files the app does not build. Rust inline tests are removed. Lean proofs are moved to
    .stage-proofs/: the `theorem`, `lemma` and `example` commands of each file, and, where a `closure` is
    given (`lean_closure`), the files the app does not import that its proofs do. Files neither imports are
    left out and listed."""
    import lean
    for d in (STAGE, PROOF_STAGE):
        shutil.rmtree(d, ignore_errors=True)
    kept, generated = counted_files(refs, skip)
    staged, proof_files, not_built = [], [], []

    def put(root, f, text):
        dest = root / f.relative_to(SOURCES_DIR)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text)
        return dest
    for f in kept:
        text = f.read_text(errors='ignore')
        if f.suffix == '.rs':
            text = strip_rust_tests(text)
        if f.suffix == '.lean':
            if closure is not None and f.resolve() not in closure[0]:
                if f.resolve() in closure[1]:
                    proof_files.append(put(PROOF_STAGE, f, text))
                else:
                    not_built.append(str(f.relative_to(SOURCES_DIR)))
                continue
            text, proofs = lean.split_proofs(text)
            if proofs.strip():
                proof_files.append(put(PROOF_STAGE, f, proofs))
        staged.append(put(STAGE, f, text))
    return staged, generated, proof_files, not_built


def cloc(args, cwd=ROOT, input_text=None):
    return subprocess.run([str(CLOC), '--quiet', '--timeout', '0', '--skip-uniqueness'] + args,
                          cwd=cwd, input=input_text, capture_output=True, text=True, check=True).stdout
